// the figures, each star moved onto the catalog's nearest bright star (within a degree and a
// half); [{ name, stars: [[ra, dec, mag]], lines }], made once
let DONE = null;
export function constellations() {
	if (DONE) return DONE;
	const raw = Uint8Array.from(atob(STARS_B64), (c) => c.charCodeAt(0)), S = new Float32Array(raw.buffer);
	const D = Math.PI / 180;
	const unit = (ra, de) => [Math.cos(de * D) * Math.cos(ra * 15 * D), Math.cos(de * D) * Math.sin(ra * 15 * D), Math.sin(de * D)];
	DONE = FIGURES.map(([name, st, lines]) => ({
		name, lines,
		stars: st.map(([ra, de]) => {
			const u = unit(ra, de);
			let best = null, bd = Math.cos(1.5 * D);
			for (let i = 0; i < STAR_COUNT; i++) {
				const m = S[i * 4 + 2];
				if (m > 4.6) continue;
				const v = unit(S[i * 4], S[i * 4 + 1]), c = u[0] * v[0] + u[1] * v[1] + u[2] * v[2];
				// (the brighter of two near stars wins a close call)
				if (c > bd || (best && c > Math.cos(0.4 * D) && m < best[2])) { bd = c; best = [S[i * 4], S[i * 4 + 1], m]; }
			}
			return best || [ra, de, 3.5];
		}),
	}));
	return DONE;
}
